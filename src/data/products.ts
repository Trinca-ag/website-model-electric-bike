// ---------------------------------------------------------------------------
// Índices pré-computados (montados uma única vez no build, não a cada request)
// ---------------------------------------------------------------------------

const BY_SLUG = new Map(PRODUCTS.map((p) => [p.slug, p]))
const BY_ID = new Map(PRODUCTS.map((p) => [p.id, p]))

/** Busca por slug e, como fallback, por id (compatibilidade com links antigos). */
export function getProduct(key: string): Product | undefined {
  return BY_SLUG.get(key) ?? BY_ID.get(key)
}

export function getProductsByCategory(cat: CategoryId): Product[] {
  return PRODUCTS.filter((p) => p.cat === cat)
}

export const FEATURED_PRODUCTS: readonly Product[] = FEATURED_IDS.map((id) =>
  BY_ID.get(id),
).filter((p): p is Product => Boolean(p))

/** Linhas existentes por categoria, na ordem em que aparecem no catálogo. */
export const LINES_BY_CATEGORY: Readonly<Record<CategoryId, string[]>> = {
  bikes: [...new Set(getProductsByCategory('bikes').map((p) => p.line))],
  patinetes: [...new Set(getProductsByCategory('patinetes').map((p) => p.line))],
  pranchas: [...new Set(getProductsByCategory('pranchas').map((p) => p.line))],
}

/** Quantos produtos existem em cada categoria — usado nos cards e filtros. */
export const COUNT_BY_CATEGORY: Readonly<Record<CategoryId, number>> = {
  bikes: getProductsByCategory('bikes').length,
  patinetes: getProductsByCategory('patinetes').length,
  pranchas: getProductsByCategory('pranchas').length,
}

/** Mapa id → slug, usado para redirecionar URLs legadas (?id=ct20s). */
export const ID_TO_SLUG: Readonly<Record<string, string>> = Object.fromEntries(
  PRODUCTS.filter((p) => p.id !== p.slug).map((p) => [p.id, p.slug]),
)
